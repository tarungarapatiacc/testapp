from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from contextlib import asynccontextmanager
import os
from dotenv import load_dotenv

load_dotenv()

# Import routers after they're created

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Startup
    print("🚀 Starting Human vs AI Assessment Platform")
    yield
    # Shutdown
    print("🛑 Shutting down application")

app = FastAPI(
    title="Human vs AI Thinking Assessment",
    description="Platform to assess out-of-the-box thinking and compare human reasoning with algorithmic approaches",
    version="1.0.0",
    lifespan=lifespan
)

# CORS middleware
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:3000", "http://localhost:8000"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/")
def read_root():
    return {
        "message": "Human vs AI Thinking Assessment Platform",
        "version": "1.0.0",
        "docs": "/docs"
    }

@app.get("/health")
def health_check():
    return {"status": "healthy"}

if __name__ == "__main__":
    import uvicorn
    uvicorn.run(
        "main:app",
        host="0.0.0.0",
        port=int(os.getenv("PORT", 8000)),
        reload=True
    )
